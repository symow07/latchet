const { withXcodeProject, withEntitlementsPlist, IOSConfig } = require("@expo/config-plugins");
const fs = require("fs");
const path = require("path");
const { iosDeploymentTarget } = require("./withIosDeploymentTarget");

/**
 * Creates the "Share to Latchet" extension target.
 *
 * A share extension has to be its own target — it is a separate binary the
 * system loads inside other apps. That is also why this one needs an App
 * Group: the extension runs in its own container and cannot see the app's, so
 * the shared container is the only ground they both stand on.
 *
 * Unlike the App Intents plugin, this cannot avoid provisioning. The App Group
 * capability must be enabled on the App ID in the Apple Developer portal or the
 * entitlement will not sign. The app degrades to "no shared inbox" without it
 * rather than failing, but the feature does not work until it is enabled.
 *
 * ios/ is gitignored and regenerated by prebuild, so the target has to be
 * rebuilt from here on every prebuild rather than created once by hand.
 */
const TARGET = "LatchetShareExtension";
const APP_GROUP = "group.com.latchet.app";
const SOURCE_DIR = path.join("plugins", "ios", "ShareExtension");
const FILES = ["ShareViewController.swift", "Info.plist", "ShareExtension.entitlements"];

/**
 * The extension's own translations.
 *
 * It is a separate bundle, so the app's .lproj files do not reach it and its
 * one piece of prose would have stayed English in a translated app.
 */
const REGIONS = ["en", "fr", "zh-Hans"];
const STRINGS_TABLE = "Localizable.strings";

/** Settings the generated target does not get right on its own. */
function buildSettings(bundleId, marketingVersion, deploymentTarget) {
  return {
    CLANG_ENABLE_MODULES: "YES",
    CODE_SIGN_ENTITLEMENTS: `"${TARGET}/ShareExtension.entitlements"`,
    CODE_SIGN_STYLE: "Automatic",
    CURRENT_PROJECT_VERSION: '"1"',
    // The target ships a hand-written Info.plist; letting Xcode generate one
    // would drop NSExtension and the extension would never be offered.
    GENERATE_INFOPLIST_FILE: "NO",
    INFOPLIST_FILE: `"${TARGET}/Info.plist"`,
    // The app's minimum, from app.json (see withIosDeploymentTarget). A value
    // of its own would drift the first time the app's is raised.
    IPHONEOS_DEPLOYMENT_TARGET: deploymentTarget,
    LD_RUNPATH_SEARCH_PATHS:
      '"$(inherited) @executable_path/Frameworks @executable_path/../../Frameworks"',
    MARKETING_VERSION: `"${marketingVersion}"`,
    PRODUCT_BUNDLE_IDENTIFIER: `"${bundleId}"`,
    PRODUCT_NAME: `"${TARGET}"`,
    SKIP_INSTALL: "YES",
    SWIFT_VERSION: '"5.0"',
    TARGETED_DEVICE_FAMILY: '"1,2"',
  };
}

module.exports = function withShareExtension(config) {
  // The app half of the App Group. Both sides must declare it or the container
  // resolves to nil in one of them.
  config = withEntitlementsPlist(config, (cfg) => {
    const existing = cfg.modResults["com.apple.security.application-groups"] ?? [];
    if (!existing.includes(APP_GROUP)) {
      cfg.modResults["com.apple.security.application-groups"] = [...existing, APP_GROUP];
    }
    return cfg;
  });

  return withXcodeProject(config, (cfg) => {
    const project = cfg.modResults;
    const projectRoot = cfg.modRequest.projectRoot;
    const platformRoot = cfg.modRequest.platformProjectRoot;

    // Prebuild reruns this against an ios/ that may already have the target.
    // Adding it twice gives two extensions with the same bundle id.
    if (project.pbxTargetByName(TARGET)) return cfg;

    const destination = path.join(platformRoot, TARGET);
    fs.mkdirSync(destination, { recursive: true });
    for (const file of FILES) {
      const from = path.join(projectRoot, SOURCE_DIR, file);
      if (!fs.existsSync(from)) {
        throw new Error(`[withShareExtension] missing ${SOURCE_DIR}/${file}`);
      }
      fs.copyFileSync(from, path.join(destination, file));
    }

    // The extension's id must be prefixed by the app's, or the system refuses
    // to install it alongside.
    const appBundleId = config.ios?.bundleIdentifier;
    if (!appBundleId) throw new Error("[withShareExtension] ios.bundleIdentifier is not set");
    const bundleId = `${appBundleId}.share`;

    project.addPbxGroup(FILES, TARGET, TARGET);

    const target = project.addTarget(TARGET, "app_extension", TARGET, bundleId);
    project.addBuildPhase([], "PBXSourcesBuildPhase", "Sources", target.uuid);
    project.addBuildPhase([], "PBXResourcesBuildPhase", "Resources", target.uuid);
    project.addBuildPhase([], "PBXFrameworksBuildPhase", "Frameworks", target.uuid);
    project.addSourceFile(
      `${TARGET}/ShareViewController.swift`,
      { target: target.uuid },
      project.findPBXGroupKey({ name: TARGET }),
    );

    for (const configuration of Object.values(project.pbxXCBuildConfigurationSection())) {
      if (typeof configuration !== "object" || !configuration.buildSettings) continue;
      if (configuration.buildSettings.PRODUCT_NAME !== `"${TARGET}"`) continue;
      Object.assign(
        configuration.buildSettings,
        buildSettings(bundleId, config.version ?? "1.0.0", iosDeploymentTarget(cfg)),
      );
    }

    // Embedding: the app has to build the extension first and carry it inside
    // its own PlugIns folder.
    //
    // Only the dependency is added here. addTarget has *already* created the
    // copy-files phase on the app target — named "Copy Files", destination 13
    // (PlugIns) — and adding a second one gives the product build file two
    // parent phases, which CocoaPods rejects outright:
    // "Consistency issue: no parent for object `LatchetShareExtension.appex`".
    const appTarget = IOSConfig.XcodeUtils.getApplicationNativeTarget({
      project,
      projectName: IOSConfig.XcodeUtils.getProjectName(projectRoot),
    });
    // addTargetDependency silently does nothing when these sections are absent,
    // and an Expo project with a single target has neither. Without the
    // dependency the app can be linked before the extension is built, and the
    // embed phase copies a product that is not there yet.
    const objects = project.hash.project.objects;
    objects.PBXTargetDependency = objects.PBXTargetDependency || {};
    objects.PBXContainerItemProxy = objects.PBXContainerItemProxy || {};
    project.addTargetDependency(appTarget.uuid, [target.uuid]);

    // The extension's own .lproj files, attached to the extension's resources
    // rather than the app's. A .xcstrings catalog is not an option here for
    // the same reason as the app: it requires iOS 17, above this app's minimum.
    const variantChildren = [];
    for (const region of REGIONS) {
      const relative = path.join(`${region}.lproj`, STRINGS_TABLE);
      const from = path.join(projectRoot, SOURCE_DIR, relative);
      if (!fs.existsSync(from)) {
        throw new Error(`[withShareExtension] missing ${SOURCE_DIR}/${relative}`);
      }
      const to = path.join(destination, relative);
      fs.mkdirSync(path.dirname(to), { recursive: true });
      fs.copyFileSync(from, to);

      const fileRef = project.generateUuid();
      objects.PBXFileReference[fileRef] = {
        isa: "PBXFileReference",
        lastKnownFileType: "text.plist.strings",
        name: region.includes("-") ? `"${region}"` : region,
        path: `"${path.join(TARGET, relative)}"`,
        sourceTree: '"<group>"',
      };
      objects.PBXFileReference[`${fileRef}_comment`] = region;
      variantChildren.push({ value: fileRef, comment: region });
    }

    objects.PBXVariantGroup = objects.PBXVariantGroup || {};
    const variantGroup = project.generateUuid();
    objects.PBXVariantGroup[variantGroup] = {
      isa: "PBXVariantGroup",
      children: variantChildren,
      name: STRINGS_TABLE,
      sourceTree: '"<group>"',
    };
    objects.PBXVariantGroup[`${variantGroup}_comment`] = STRINGS_TABLE;

    const stringsBuildFile = project.generateUuid();
    objects.PBXBuildFile[stringsBuildFile] = { isa: "PBXBuildFile", fileRef: variantGroup };
    objects.PBXBuildFile[`${stringsBuildFile}_comment`] = `${STRINGS_TABLE} in Resources`;

    // By key. Passed an object, the xcode library uses its `fileRef` as the
    // child; a variant group has none, so the group got an `undefined`
    // child, which CocoaPods warned about on every install and dropped.
    project.addToPbxGroup(variantGroup, project.findPBXGroupKey({ name: TARGET }));
    project.pbxResourcesBuildPhaseObj(target.uuid).files.push({
      value: stringsBuildFile,
      comment: `${STRINGS_TABLE} in Resources`,
    });

    return cfg;
  });
};
